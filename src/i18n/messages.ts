const TABLE: Record<Lang, Record<MessageKey, string>> = { en, ja, my }

/** The sentence for `key` in `lang`, with {name} placeholders filled in. */
export function t(lang: Lang, key: MessageKey, params: Record<string, string | number> = {}): string {
  const text = TABLE[lang]?.[key] ?? en[key]
  return text.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`))
}

